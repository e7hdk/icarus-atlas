const cities = JSON.parse(fs.readFileSync(CITIES_FILE, 'utf8'));
const places = JSON.parse(fs.readFileSync(PLACES_FILE, 'utf8'));
const cityIds = new Set(cities.map((c) => c.id));
const placeIds = new Set(places.map((p) => p.id));

let added = 0;
for (const city of NEW_CITIES) {
  if (cityIds.has(city.id)) continue;

  cities.push({
    id: city.id,
    name: city.name,
    greekName: city.greekName,
    region: city.region,
    coordinates: city.coordinates,
    pleiadesId: city.pleiadesId,
  });

  places.push({
    id: city.id,
    name: city.name,
    greekName: city.greekName,
    kind: 'city',
    region: city.region,
    coordinates: city.coordinates,
    certainty: city.certainty ?? 'fixed',
    pleiadesId: city.pleiadesId,
    importance: city.importance,
    cityId: city.id,
    summary: [city.summary],
  });

  added++;
  console.log(`${DRY ? '[dry-run] ' : ''}added city ${city.id}`);
}

if (!DRY && added > 0) {
  fs.writeFileSync(CITIES_FILE, `${JSON.stringify(cities, null, 2)}\n`);
  fs.writeFileSync(PLACES_FILE, `${JSON.stringify(places, null, 2)}\n`);
}

console.log(`\n${DRY ? 'Would add' : 'Added'} ${added} cities (${cityIds.size} → ${cityIds.size + added})`);
