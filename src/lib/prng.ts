/** Deterministic PRNG helpers shared by the galaxy layout, the spindle and the
 *  Ephemeris. Everything seeded from these must be stable across sessions and
 *  machines — the sky never rearranges between visits, and the star of the day
 *  is the same star for every visitor. */

/** FNV-1a — stable across sessions so the sky never rearranges between visits. */
export function hashString(input: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

export function mulberry32(seed: number): () => number {
  let a = seed;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
