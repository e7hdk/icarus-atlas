/** Build a MapLibre match expression for region fill colours. */
export function regionColorMatch(defaultColor = '#7c4dff'): unknown[] {
  const pairs: unknown[] = ['match', ['get', 'id']];
  for (const [id, color] of Object.entries(REGION_HUE)) {
    pairs.push(id, color);
  }
  pairs.push(defaultColor);
  return pairs;
}
